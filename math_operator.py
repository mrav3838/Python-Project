def multiply(a, b):
    print(a * b)

# 4.
def divide(a, b):
    print(a / b)

# 5.
def floor_divide(a, b):
    print(a // b)

# 6.
def modulus(a, b):
    print(a % b)

# 7.
def power(a, b):
    print(a ** b)

# 8.
